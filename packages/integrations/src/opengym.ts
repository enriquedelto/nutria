/**
 * openGym integration (self-hosted gym tracker, https://gitlab.com/DuarteSantos8/opengym). Read-only.
 * Auth: openGym → Settings → "Pair the mobile app" gives an 8-character code → POST /api/pair/redeem
 * → Bearer token valid SESSION_DAYS (90); GET /api/me hands out a renewed one past half its life.
 * Read: GET /api/data/rev (cheap poll) and GET /api/data → { state: { unit, workouts[], bodyweight[] }, rev }.
 * openGym sends no webhooks, so Nutria polls.
 */
import { strengthSessionKcal } from "@nutria/nutrition";
import EXERCISE_NAMES from "./opengym-exercises.json";

export interface OpenGymWorkout {
  id: string;
  d: string;
  start?: number;
  end?: number;
  name?: string;
  routineId?: string;
  bw?: number;
  vol?: number;
  prs?: string[];
  entries?: { id: string; sets?: { w?: number; r?: number; done?: boolean }[] }[];
}
export interface OpenGymWeighIn {
  d: string;
  w: number;
  t?: number;
}
export interface OpenGymState {
  unit?: "kg" | "lb";
  workouts?: OpenGymWorkout[];
  bodyweight?: OpenGymWeighIn[];
  customEx?: { id: string; name?: string }[];
}

/** Catalogue exercise id → Spanish name (generated by scripts/opengym-exercises.mjs). */
const CATALOGUE = EXERCISE_NAMES as Record<string, string>;

const LB = 0.45359237;

export class OpenGymClient {
  constructor(
    private baseUrl: string,
    private token?: string,
    private f: typeof fetch = fetch,
  ) {
    this.baseUrl = baseUrl.replace(/\/$/, "");
  }

  async redeem(code: string, deviceName = "Nutria"): Promise<string> {
    const r = await this.f(`${this.baseUrl}/api/pair/redeem`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ code: code.trim(), name: deviceName }),
      signal: AbortSignal.timeout(10000),
    });
    if (!r.ok) throw new Error(r.status === 400 || r.status === 404 ? "Código de emparejamiento no válido o caducado" : `openGym respondió ${r.status}`);
    const j = (await r.json()) as { token?: string };
    if (!j.token) throw new Error("openGym no devolvió token");
    this.token = j.token;
    return j.token;
  }

  private headers() {
    if (!this.token) throw new Error("Sin token de openGym");
    return { Authorization: `Bearer ${this.token}`, Accept: "application/json" };
  }

  /** Returns state and, if the server renewed the token, the new token. */
  async me(): Promise<{ name?: string; renewedToken?: string }> {
    const r = await this.f(`${this.baseUrl}/api/me`, { headers: this.headers(), signal: AbortSignal.timeout(10000) });
    if (r.status === 401) throw new Error("Token de openGym caducado: vuelve a emparejar");
    const j = (await r.json()) as { user?: { name?: string }; name?: string; token?: string };
    return { name: j.user?.name ?? j.name, renewedToken: j.token };
  }

  /** Current revision of the state, without the document (cheap to poll). */
  async rev(): Promise<number> {
    const r = await this.f(`${this.baseUrl}/api/data/rev`, { headers: this.headers(), signal: AbortSignal.timeout(10000) });
    if (r.status === 401) throw new Error("Token de openGym caducado: vuelve a emparejar");
    if (!r.ok) throw new Error(`openGym respondió ${r.status}`);
    return Number(((await r.json()) as { rev?: number }).rev ?? 0);
  }

  async data(): Promise<{ state: OpenGymState | null; rev: number }> {
    const r = await this.f(`${this.baseUrl}/api/data`, { headers: this.headers(), signal: AbortSignal.timeout(20000) });
    if (r.status === 401) throw new Error("Token de openGym caducado: vuelve a emparejar");
    if (!r.ok) throw new Error(`openGym respondió ${r.status}`);
    return (await r.json()) as { state: OpenGymState | null; rev: number };
  }
}

export interface WorkoutDetails {
  exercises: { id: string; name: string; sets: { kg: number | null; reps: number | null }[] }[];
  prs: string[];
}
export interface MappedExercise {
  externalId: string;
  date: string;
  startedAt: Date | null;
  name: string;
  durationMin: number;
  kcal: number;
  volumeKg: number | null;
  sets: number;
  details: WorkoutDetails;
}
export interface MappedWeight {
  externalId: string;
  date: string;
  measuredAt: Date;
  kg: number;
}

/**
 * Map openGym state into our exercise/weight rows (idempotent by externalId: workout id, and the
 * day for weigh-ins, which is how openGym itself keys them). Exercise names come from the openGym
 * catalogue or the user's custom exercises.
 */
export function mapOpenGymState(state: OpenGymState, fallbackWeightKg: number): { exercises: MappedExercise[]; weights: MappedWeight[] } {
  const toKg = (v: number) => (state.unit === "lb" ? v * LB : v);
  const custom = new Map((state.customEx ?? []).filter((c) => c?.id).map((c) => [c.id, c.name]));
  const exName = (id: string) => custom.get(id) || CATALOGUE[id] || "Ejercicio";
  const byDay = new Map<string, OpenGymWeighIn>();
  for (const b of state.bodyweight ?? []) {
    if (!b?.d || !Number.isFinite(b.w) || b.w <= 0) continue;
    const prev = byDay.get(b.d);
    if (!prev || (b.t ?? 0) >= (prev.t ?? 0)) byDay.set(b.d, b);
  }
  const weights: MappedWeight[] = [...byDay.values()].map((b) => ({ externalId: `bw:${b.d}`, date: b.d, measuredAt: new Date(b.t ?? Date.parse(`${b.d}T08:00:00`)), kg: Math.round(toKg(b.w) * 100) / 100 }));
  const exercises: MappedExercise[] = (state.workouts ?? [])
    .filter((w) => w?.id && w.d)
    .map((w) => {
      const minutes = w.start && w.end && w.end > w.start ? Math.min(240, (w.end - w.start) / 60000) : 45;
      const bodyKg = w.bw ? toKg(w.bw) : fallbackWeightKg;
      const vol = w.vol != null ? toKg(w.vol) : null;
      const sets = (w.entries ?? []).reduce((s, e) => s + (e.sets ?? []).filter((x) => x.done !== false).length, 0);
      const details: WorkoutDetails = {
        exercises: (w.entries ?? [])
          .filter((e) => e?.id)
          .map((e) => ({
            id: e.id,
            name: exName(e.id),
            sets: (e.sets ?? []).filter((x) => x && x.done !== false).map((x) => ({ kg: Number.isFinite(x.w) ? Math.round(toKg(x.w!) * 10) / 10 : null, reps: Number.isFinite(x.r) ? x.r! : null })),
          })),
        prs: (w.prs ?? []).map(exName),
      };
      return {
        externalId: w.id,
        date: w.d,
        startedAt: w.start ? new Date(w.start) : null,
        name: w.name || "Entrenamiento (openGym)",
        durationMin: Math.round(minutes),
        kcal: strengthSessionKcal(bodyKg, minutes, vol ?? undefined),
        volumeKg: vol == null ? null : Math.round(vol),
        sets,
        details,
      };
    });
  return { exercises, weights };
}
